"""Regenerates the README feature table from registry/features.json between the FEATURES markers.
Usage: python scripts/sync_readme.py          # rewrite
       python scripts/sync_readme.py --check  # exit 1 if README is stale (used in CI)"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- FEATURES:START (generated by scripts/sync_readme.py from registry/features.json) -->", "<!-- FEATURES:END -->"
ICON = {"verified": "✅ verified", "partial": "🟠 partial", "blocked": "⛔ blocked (external)", "not_done": "⬜ not done"}


def render() -> str:
    feats = json.loads((ROOT / "registry" / "features.json").read_text())["features"]
    rows = ["| Feature | Status | Evidence | Origin |", "|---|---|---|---|"]
    rows += [f"| {f['name']} | {ICON[f['status']]} | {f['evidence']} | {f['source']} |" for f in feats]
    c = {k: sum(1 for f in feats if f["status"] == k) for k in ICON}
    return f"{START}\n\n{' · '.join(f'{ICON[k]}: {v}' for k, v in c.items())}\n\n" + "\n".join(rows) + f"\n\n{END}"


def main() -> int:
    p = ROOT / "README.md"
    s = p.read_text()
    if START not in s or END not in s:
        print("README markers missing")
        return 1
    new = s[: s.index(START)] + render() + s[s.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != s:
            print("README feature table is stale: run python scripts/sync_readme.py")
            return 1
        print("README feature table is current")
        return 0
    p.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
