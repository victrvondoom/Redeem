"""Brief -> structured document -> real PDF. Deterministic extraction (no LLM): headings, bullet points, action items and key facts are taken
from the user's own text and shown for editing before anything is rendered. The PDF carries the source hash as provenance."""
from __future__ import annotations

import hashlib
import io
import re
from datetime import datetime, timezone

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer
from xml.sax.saxutils import escape

ACTION = re.compile(r"\b(need to|needs to|must|should|todo|to do|action|follow up|follow-up|deadline|by \w+day|please)\b", re.I)
DATE = re.compile(r"\b(\d{1,2}[ /-](?:\d{1,2}|[A-Za-z]{3,9})[ /-]\d{2,4}|\d{4}-\d{2}-\d{2})\b")
MONEY = re.compile(r"(?:Rs\.?|INR|₹|\$)\s?\d[\d,]*(?:\.\d+)?")
REF = re.compile(r"\b[A-Z]{2}\d{3,4}\b|\b[A-Z]{2,5}-\d{3,}\b")


def extract(brief: str) -> dict:
    brief = brief.strip()
    lines = [ln.rstrip() for ln in brief.splitlines()]
    sections: list[dict] = []
    cur = {"heading": "Summary", "paragraphs": [], "bullets": []}
    first_heading = None
    for ln in lines:
        t = ln.strip()
        if not t:
            continue
        m = re.match(r"^(#{1,3})\s+(.*)$", t) or (re.match(r"^([A-Z][^.!?]{2,60}):$", t) and re.match(r"^()(.*):$", t))
        if m:
            first_heading = first_heading or m.group(2).strip()
            if cur["paragraphs"] or cur["bullets"]:
                sections.append(cur)
            cur = {"heading": m.group(2).strip(), "paragraphs": [], "bullets": []}
        elif re.match(r"^[-*•]\s+", t):
            cur["bullets"].append(re.sub(r"^[-*•]\s+", "", t))
        else:
            cur["paragraphs"].append(t)
    if cur["paragraphs"] or cur["bullets"]:
        sections.append(cur)
    body = " ".join(lines)
    items = [ln.strip("-*• ").strip() for ln in lines if ln.strip() and ACTION.search(ln)]
    facts = {"dates": sorted(set(DATE.findall(body))), "amounts": sorted(set(MONEY.findall(body))), "references": sorted(set(REF.findall(body)))}
    title = first_heading or next((s["heading"] for s in sections if s["heading"] != "Summary"), None) or (lines[0].strip("# ").strip()[:80] if lines and lines[0].strip() else "Brief")
    return {"title": title, "sections": sections, "action_items": items[:20], "facts": facts, "source_sha256": hashlib.sha256(brief.encode()).hexdigest(), "word_count": len(brief.split())}


def render(structured: dict, author: str) -> bytes:
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=22, leading=26, spaceAfter=10)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=14, leading=18, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10.5, leading=15)
    small = ParagraphStyle("s", parent=ss["BodyText"], fontSize=8.5, leading=11, textColor="#555555")
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=18 * mm, title=structured["title"], author=author)
    st = [Paragraph(escape(structured["title"]), h1)]
    for sec in structured["sections"]:
        st.append(Paragraph(escape(sec["heading"]), h2))
        for p in sec.get("paragraphs", []):
            st.append(Paragraph(escape(p), body))
        if sec.get("bullets"):
            st.append(ListFlowable([ListItem(Paragraph(escape(b), body)) for b in sec["bullets"]], bulletType="bullet", leftIndent=14))
    if structured.get("action_items"):
        st.append(Paragraph("Action items", h2))
        st.append(ListFlowable([ListItem(Paragraph(escape(a), body)) for a in structured["action_items"]], bulletType="bullet", leftIndent=14))
    f = structured.get("facts") or {}
    rows = [(k.title(), ", ".join(v)) for k, v in f.items() if v]
    if rows:
        st.append(Paragraph("Key facts found in the brief", h2))
        for k, v in rows:
            st.append(Paragraph(f"<b>{escape(k)}:</b> {escape(v)}", body))
    st += [Spacer(1, 10 * mm), Paragraph(escape(f"Generated by REDEEM on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} from a brief with SHA-256 {structured.get('source_sha256', '')[:16]}. Content is the author's own; nothing was added."), small)]
    doc.build(st)
    return buf.getvalue()
