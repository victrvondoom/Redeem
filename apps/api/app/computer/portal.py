@router.post("/{key}/api/submissions", status_code=201)
def submit(key: str, body: dict = Body(...), db=Depends(get_db)):
    tenant = _check_key(db, key)
    docs = body.get("documents") or []
    if not isinstance(docs, list) or not all(isinstance(d, str) for d in docs):
        raise err(422, "invalid", "documents must be a list of names")
    p = payload(str(body.get("case_ref", "")), str(body.get("department", "")), str(body.get("claim_summary", "")), str(body.get("amount_inr", "")), docs)
    if not p["case_ref"] or len(p["case_ref"]) > 60:
        raise err(422, "invalid", "Case reference is required")
    if p["department"] not in DEPARTMENTS:
        raise err(422, "invalid", "Choose a department")
    if not p["claim_summary"] or len(p["claim_summary"]) > 1000:
        raise err(422, "invalid", "Claim summary is required (max 1000 characters)")
    if p["amount_inr"] and not re.fullmatch(r"\d{1,9}(\.\d{1,2})?", p["amount_inr"]):
        raise err(422, "invalid", "Amount must be a number such as 1250 or 1250.50")
    dg = payload_digest(p)
    dup = db.scalar(select(PortalSubmission).where(PortalSubmission.workspace_key == key, PortalSubmission.payload_digest == dg))
    if dup:
        raise err(409, "duplicate_submission", "This exact request was already received", acknowledgement_id=dup.acknowledgement_id)
    ack = "RCP-" + "".join(secrets.choice(ACK_ALPHABET) for _ in range(8))
    row = PortalSubmission(tenant_id=tenant, workspace_key=key, case_ref=p["case_ref"], portal_id=PORTAL_ID, form_version=FORM_VERSION, fields={k: p[k] for k in FIELDS},
                           documents=p["documents"], payload_digest=dg, status="RECEIVED", acknowledgement_id=ack,
                           portal_response={"message": "Received by the REDEEM case portal. This is a REDEEM-owned system; nothing was filed with an external party.", "external_filing": False})
    db.add(row)
    try:
        db.commit()
    except IntegrityError:
        db.rollback()
        raise err(409, "duplicate_submission", "This exact request was already received")
    return as_json(row)


@router.get("/{key}/api/submissions")
def list_submissions(key: str, case_ref: str = "", db=Depends(get_db)):
    _check_key(db, key)
    q = select(PortalSubmission).where(PortalSubmission.workspace_key == key).order_by(PortalSubmission.submitted_at.desc())
    if case_ref:
        q = q.where(PortalSubmission.case_ref == case_ref)
    return {"items": [as_json(r) for r in db.scalars(q.limit(50))]}


@router.get("/{key}/api/submissions/{ack}")
def get_submission(key: str, ack: str, db=Depends(get_db)):
    _check_key(db, key)
    r = db.scalar(select(PortalSubmission).where(PortalSubmission.workspace_key == key, PortalSubmission.acknowledgement_id == ack))
    if not r:
        raise err(404, "not_found", "No submission with that acknowledgement ID")
    return as_json(r)
