"""REDEEM case portal: a first-party, REDEEM-owned execution target for the "consumer case via portal" scenario.

It is NOT an airline, bank or government system. A submission here is stored in `portal_submissions` and acknowledged with
an ID generated by this server; nothing is filed with any external party. The page is meant to be operated through its
visible form by the computer agent. The access key is the per-workspace unguessable key shared with the demo CRM."""
from __future__ import annotations

import hashlib
import html
import json
import re
import secrets

from fastapi import APIRouter, Body, Depends
from fastapi.responses import HTMLResponse
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError

from ..core.deps import err
from ..db import get_db
from ..models import DemoCrmContact, PortalSubmission

router = APIRouter(prefix="/portal", tags=["case-portal"])
PORTAL_ID, FORM_VERSION = "redeem-case-portal", "1"
DEPARTMENTS = ["Customer Relations", "Billing", "Escalations"]
ACK_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
FIELDS = ("case_ref", "department", "claim_summary", "amount_inr", "documents")


def payload(case_ref: str, department: str, claim_summary: str, amount_inr: str, documents: list[str]) -> dict:
    return {"portal_id": PORTAL_ID, "form_version": FORM_VERSION, "case_ref": case_ref.strip(), "department": department.strip(), "claim_summary": " ".join(claim_summary.split()),
            "amount_inr": amount_inr.strip(), "documents": [d.strip() for d in documents if d.strip()], "action": "submit_request"}


def payload_digest(p: dict) -> str:
    return hashlib.sha256(json.dumps(p, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def workspace_key(db, tenant_id: str) -> str:
    from . import demo_crm
    return demo_crm.ensure(db, tenant_id)


def _check_key(db, key: str) -> str:
    row = db.scalar(select(DemoCrmContact).where(DemoCrmContact.workspace_key == key))
    if not row:
        raise err(404, "not_found", "Unknown portal")
    return row.tenant_id


def as_json(r: PortalSubmission) -> dict:
    return {"id": r.id, "case_ref": r.case_ref, "portal_id": r.portal_id, "form_version": r.form_version, "fields": r.fields, "documents": r.documents,
            "payload_digest": r.payload_digest, "approval_ref": r.approval_ref, "status": r.status, "acknowledgement_id": r.acknowledgement_id,
            "portal_response": r.portal_response, "submitted_at": r.submitted_at.isoformat()}


