import io

from pypdf import PdfReader
from sqlalchemy import text

B = "/api/v1/studio/brief"
BRIEF = """# Q4 refund follow-up
Customer Asha Rao reports flight FA2041 was cancelled on 2026-10-14.

Findings:
- Refund of Rs 8,450 was promised but not received
- Hotel booking BK-2231 needs to be moved
We should follow up with the airline by Friday.
"""


def test_extraction_finds_sections_actions_and_facts_without_inventing(api):
    r = api.post(f"{B}/extract", {"brief": BRIEF}).json()
    assert r["title"] == "Q4 refund follow-up" and [s["heading"] for s in r["sections"]] == ["Q4 refund follow-up", "Findings"]
    assert r["sections"][1]["bullets"][0].startswith("Refund of Rs 8,450")
    assert "2026-10-14" in r["facts"]["dates"] and "Rs 8,450" in r["facts"]["amounts"] and {"FA2041", "BK-2231"} <= set(r["facts"]["references"])
    assert any("follow up" in a.lower() for a in r["action_items"]) and r["source_sha256"] and api.post(f"{B}/extract", {"brief": "short"}).status_code == 422


def test_edited_structure_renders_a_real_pdf_stored_encrypted_with_provenance(api, api2, db):
    s = api.post(f"{B}/extract", {"brief": BRIEF}).json()
    s["title"] = "Edited title"
    s["sections"][1]["bullets"].append("Extra bullet added by the user")
    out = api.post(f"{B}/render", {"structured": s, "domain": "travel"}).json()
    assert out["pages"] == 1 and out["download"].endswith("/download")
    pdf = api.get(out["download"]).content
    assert pdf[:5] == b"%PDF-"
    txt = "\n".join(p.extract_text() for p in PdfReader(io.BytesIO(pdf)).pages)
    assert "Edited title" in txt and "Extra bullet added by the user" in txt and "FA2041" in txt and "Generated by REDEEM" in txt
    d = api.get(f"/api/v1/documents/{out['document_id']}").json()
    assert d["extracted"]["provenance"]["source_sha256"] == s["source_sha256"] and d["domain"] == "travel"
    blob = open(db.execute(text("select blob_path from documents where id=:i"), {"i": out["document_id"]}).scalar(), "rb").read()
    assert blob.startswith(b"RDM2") and b"%PDF" not in blob[:40]
    assert api2.get(out["download"]).status_code == 404
    assert api.post(f"{B}/render", {"structured": {"title": "x", "sections": [], "action_items": []}}).status_code == 422
